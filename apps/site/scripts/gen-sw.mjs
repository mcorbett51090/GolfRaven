#!/usr/bin/env node
/**
 * gen-sw.mjs — generates `<dist>/sw.js`, build plan §5.1 `sw.js`: "Adapt |
 * same | Cache `gr-v1`; app name 'GolfRaven'." Runs POSTBUILD (same
 * position/reasoning as `gen-headers.mjs`/`gen-redirects.mjs` — writes
 * straight into `dist`, never a tracked `public/sw.js`, and a build id
 * needs to exist before it can be embedded).
 *
 * **Opus gate should-fix ("Service worker") — every change from the
 * stage-2 original, and why:**
 *
 * - **Cache name carries a build id** (`gr-<buildId>`, `GOLFRAVEN_BUILD_ID`
 *   env override, default `Date.now()`). Every build is a fresh cache
 *   epoch; `activate` deletes every OTHER cache outright (no more
 *   "copy-forward merge" — a new deploy's cache starts clean).
 * - **Network-first, not cache-first, for every NON-hashed same-origin
 *   path** — navigations (unchanged from stage 2) PLUS `/data/map/*`
 *   (per-country GeoJSON, regenerated on every build with no hash in its
 *   URL), `/catalog/v1/*` (the future public catalog JSON, same story),
 *   and `/pagefind/pagefind-entry.json` (Pagefind's own small manifest,
 *   NOT content-hashed like its `pagefind.<lang>_<hash>.pf_meta`/wasm
 *   siblings are). Everything ELSE stays cache-first (content-hashed
 *   `/_astro/*` chunks, OG PNGs, Pagefind's hashed index shards) — a
 *   cached copy of a hashed asset is never the wrong copy.
 * - **A 404/410 evicts the cached copy** — a page removed since the
 *   visitor's last visit (an unpublished course, a retired redirect
 *   target) must not keep being served stale from cache forever once the
 *   origin says it's gone.
 * - **`./trails/` removed from `SHELL`** — `/trails/` (the plural
 *   directory) is not a route this site serves at all (the hub is `/`;
 *   `/trails/<slug>/` is the only real path under that prefix), so
 *   pre-caching it during `install` was requesting a 404 on every fresh
 *   install.
 * - **Not registered in demo builds** — see `BaseLayout.astro`'s
 *   `{!demo && (<script>...)}` guard; this file itself has no way to know
 *   whether IT should exist, so the guard lives entirely on the
 *   registration side.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

export function buildSwSource(env = process.env) {
  const buildId = env.GOLFRAVEN_BUILD_ID?.trim() || String(Date.now());
  return `/**
 * sw.js — GENERATED by scripts/gen-sw.mjs, do not hand-edit.
 * GolfRaven service worker (offline + installable). Build id: ${buildId}
 */
const CACHE = "gr-${buildId}";
const HOME = new URL("./", self.registration.scope).href;
const SHELL = ["./", "./claim/", "./feedback/", "./fr/"];
const NAV_TIMEOUT_MS = 3000;

// Same-origin paths that are network-first even though they aren't page
// navigations — none of these carry a content hash in their URL.
function isNetworkFirst(pathname) {
  return (
    pathname === "/pagefind/pagefind-entry.json" ||
    pathname.startsWith("/data/map/") ||
    pathname.startsWith("/catalog/")
  );
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => Promise.allSettled(SHELL.map((u) => cache.add(u))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(names.filter((n) => n !== CACHE).map((n) => caches.delete(n)));
      await self.clients.claim();
    })(),
  );
});

async function networkFirst(req, cache) {
  let timer;
  try {
    const res = await Promise.race([
      fetch(req).then((r) => {
        if (r && r.ok && r.type === "basic") cache.put(req, r.clone());
        if (r && (r.status === 404 || r.status === 410)) cache.delete(req);
        return r;
      }),
      new Promise((_, reject) => {
        timer = setTimeout(() => reject(new Error("nav-timeout")), NAV_TIMEOUT_MS);
      }),
    ]);
    if (res) return res;
  } catch {
    /* offline/error/slow -> fall through to cache */
  } finally {
    clearTimeout(timer);
  }
  return (await cache.match(req)) || (req.mode === "navigate" ? await cache.match(HOME) : undefined) || Response.error();
}

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // external tile host -> default network

  if (req.mode === "navigate" || isNetworkFirst(url.pathname)) {
    event.respondWith(caches.open(CACHE).then((cache) => networkFirst(req, cache)));
    return;
  }

  // Everything else: cache-first, refreshed in the background — safe
  // because every remaining path is content-hashed (a cached copy is
  // never the wrong copy). A 404/410 still evicts, same as network-first.
  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      const cached = await cache.match(req);
      const network = fetch(req)
        .then((res) => {
          if (res && res.ok && res.type === "basic") cache.put(req, res.clone());
          if (res && (res.status === 404 || res.status === 410)) cache.delete(req);
          return res;
        })
        .catch(() => null);
      return cached || (await network) || Response.error();
    }),
  );
});
`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const distDir = process.env.DIST_DIR ?? process.argv[2] ?? join(here, "..", "dist");
  const outPath = join(distDir, "sw.js");
  await mkdir(distDir, { recursive: true });
  await writeFile(outPath, buildSwSource());
  console.log(`gen-sw: wrote ${outPath}`);
}
