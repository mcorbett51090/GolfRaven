Deno.test(
  "S5: a hand-over token minted through the handler redeems with the plaintext it returned: the stored hash is the independent SHA-256 of that plaintext, the plaintext is stored nowhere, and the redeem moves the entitlement, the stock, the movement and the token",
  DT,
  async () => {
    const staff = await newStaff(FAC);
    const player = await newPlayer();
    const ent = await newEntitlement(player);
    await setStock(5);

    const minted = await mint(staff, ent);
    assertEquals(minted.status, 201, await minted.clone().text());
    const { token, expiresAt } = (await minted.json()).data as {
      token: string;
      expiresAt: string;
    };
    assert(/^gr_ho_/.test(token), "the Edge's token format");
    const ttlMs = Date.parse(expiresAt) - Date.now();
    assert(
      ttlMs > 13 * 60_000 && ttlMs <= 15 * 60_000,
      `expires in about 15 minutes (${ttlMs} ms)`,
    );

    const [row] = await tokenRowsOf(ent);
    assertEquals(
      row!.token_hash,
      await sha256(token),
      "the database holds the SHA-256 of the plaintext the player was shown",
    );
    assertEquals(
      [row!.facility_id, row!.issued_by, row!.consumed_at],
      [FAC, staff.uid, null],
    );
    assert(
      !JSON.stringify(row).includes(token),
      "the plaintext is not in the row",
    );

    const res = await redeem(staff, ent, "hand_over_token", token);
    assertEquals(res.status, 201, await res.clone().text());
    const data = (await res.json()).data as {
      attestationId: string;
      movement: string;
      availability: string;
    };
    assert(/^[0-9a-f-]{36}$/.test(data.attestationId), "an attestation uuid");
    assertEquals(data.movement, "redeemed");

    const e = await entRow(ent);
    assertEquals(
      [e.state, e.method, e.by_staff, e.facility, e.jti],
      [
        "redeemed",
        "hand_over_token",
        staff.uid,
        FAC,
        "handover:" + (await sha256(token)),
      ],
    );
    assertEquals(await stockOf(), 4, "one unit left the shelf");
    assertEquals(await movementsOf(ent), [
      { kind: "redeemed", qty: -1, by_member: staff.uid },
    ]);
    const [spent] = await tokenRowsOf(ent);
    assertEquals(spent!.consumed_by, staff.uid);
    assert(spent!.consumed_at instanceof Date, "the token is consumed");

    // the entitlement is spent, so the same token again is refused (and nothing moves)
    const again = await redeem(staff, ent, "hand_over_token", token);
    assertEquals([again.status, await errOf(again)], [422, "not_redeemable"]);
    assertEquals(await stockOf(), 4);
  },
);

