const rs: SoftwareAuthenticator[] = [];
for (let i = 0; i < N_RS; i++) rs.push(await SoftwareAuthenticator.create("RS256"));
const rsOther = await SoftwareAuthenticator.create("RS256");
for (const a of rs) {
  const { msg, sig } = await assertion(a);
  row("RS256", "valid (2048-bit)", true, a.keyParams.n!, a.keyParams.e!, msg, sig, SA);
}
{
  const a = rs[0]!;
  const { msg, sig } = await assertion(a);
  const { n, e } = a.keyParams;
  const flip = (b: Uint8Array, at: number) => Uint8Array.from(b, (v, i) => (i === (at < 0 ? b.length + at : at) ? v ^ 1 : v));
  row("RS256", "bad: last signature bit flipped", false, n!, e!, msg, flip(sig, -1), SA);
  row("RS256", "bad: one message bit flipped", false, n!, e!, flip(msg, 5), sig, SA);
  row("RS256", "bad: another authenticator's key", false, rsOther.keyParams.n!, rsOther.keyParams.e!, msg, sig, SA);
  row("RS256", "bad: signature one byte short", false, n!, e!, msg, sig.slice(1), SA);
  row("RS256", "bad: signature equal to the modulus", false, n!, e!, msg, n!, SA);
  row("RS256", "bad: signature all 0xff (above the modulus)", false, n!, e!, msg, new Uint8Array(256).fill(0xff), SA);
  row("RS256", "bad: signature = 1", false, n!, e!, msg, bytesOf(1n, 256), SA);
  row("RS256", "bad: signature = 0", false, n!, e!, msg, new Uint8Array(256), SA);
  row("RS256", "bad: exponent 3 supplied", false, n!, Uint8Array.of(3), msg, sig, SA);
  row("RS256", "bad: exponent 65537 with a leading zero byte is still 65537 (accepted by value)", true, n!, Uint8Array.of(0, 1, 0, 1), msg, sig, SA);
}
// RSA signatures built OUTSIDE the authenticator, so the padding can be wrong in chosen ways: raw private-key operation with BigInt on a Web Crypto key.
{
  const kp = await crypto.subtle.generateKey({ name: "RSASSA-PKCS1-v1_5", modulusLength: 2048, publicExponent: Uint8Array.of(1, 0, 1), hash: "SHA-256" }, true, ["sign", "verify"]);
  const jwk = await crypto.subtle.exportKey("jwk", kp.privateKey);
  const n = fromB64u(jwk.n!);
  const e = fromB64u(jwk.e!);
  const nBig = bigOf(n);
  const dBig = bigOf(fromB64u(jwk.d!));
  const modexp = (b: bigint, x: bigint, m: bigint) => {
    let r = 1n;
    b %= m;
    while (x > 0n) {
      if (x & 1n) r = (r * b) % m;
      x >>= 1n;
      b = (b * b) % m;
    }
    return r;
  };
  const msg = crypto.getRandomValues(new Uint8Array(69));
  const h = await sha256(msg);
  const prefix = fromHex("3031300d060960864801650304020105000420");
  const rawSign = (em: Uint8Array) => bytesOf(modexp(bigOf(em), dBig, nBig), 256);
  const k = 256;
  const emGood = concat(Uint8Array.of(0, 1), new Uint8Array(k - 3 - prefix.length - 32).fill(0xff), Uint8Array.of(0), prefix, h);
  row("RS256", "valid: hand-built EMSA-PKCS1-v1_5 signed with a raw private-key operation (checks the fixture path)", true, n, e, msg, rawSign(emGood), "bigint-raw-rsa");
  // Bleichenbacher-shaped: a SHORT padding string and four garbage bytes after the hash, so a parser that stops at the DigestInfo accepts it
  const emTrailing = concat(Uint8Array.of(0, 1), new Uint8Array(k - 3 - prefix.length - 32 - 4).fill(0xff), Uint8Array.of(0), prefix, h, Uint8Array.of(0xde, 0xad, 0xbe, 0xef));
  row("RS256", "bad: padding string shortened and 4 garbage bytes after the hash (lenient-parser forgery shape)", false, n, e, msg, rawSign(emTrailing), "bigint-raw-rsa");
  // a zero byte inside the 0xff padding string
  const emHole = Uint8Array.from(emGood);
  emHole[20] = 0x00;
  row("RS256", "bad: a 0x00 byte inside the 0xff padding string", false, n, e, msg, rawSign(emHole), "bigint-raw-rsa");
  // block type 0x02 instead of 0x01
  const emType = Uint8Array.from(emGood);
  emType[1] = 0x02;
  row("RS256", "bad: block type 0x02", false, n, e, msg, rawSign(emType), "bigint-raw-rsa");
  // a properly padded signature over a SHA-384 DigestInfo (RSASSA-PKCS1-v1_5/SHA-384 straight from Web Crypto): valid RSA, wrong hash for RS256
  const sig384 = new Uint8Array(await crypto.subtle.sign("RSASSA-PKCS1-v1_5", await crypto.subtle.importKey("jwk", { ...jwk, alg: undefined }, { name: "RSASSA-PKCS1-v1_5", hash: "SHA-384" }, false, ["sign"]), msg as Uint8Array<ArrayBuffer>));
  row("RS256", "bad: a valid PKCS#1 v1.5 signature but over a SHA-384 DigestInfo", false, n, e, msg, sig384, "webcrypto");
}
// a 4096-bit key: not what authenticators emit, but the cost ceiling the 'RSA, 2048 bits or more' rule allows
{
  const kp = await crypto.subtle.generateKey({ name: "RSASSA-PKCS1-v1_5", modulusLength: 4096, publicExponent: Uint8Array.of(1, 0, 1), hash: "SHA-256" }, true, ["sign", "verify"]);
  const jwk = await crypto.subtle.exportKey("jwk", kp.publicKey);
  const msg = crypto.getRandomValues(new Uint8Array(69));
  const sig = new Uint8Array(await crypto.subtle.sign("RSASSA-PKCS1-v1_5", kp.privateKey, msg as Uint8Array<ArrayBuffer>));
  row("RS256", "valid (4096-bit; the upper bound the verifier accepts)", true, fromB64u(jwk.n!), fromB64u(jwk.e!), msg, sig, "webcrypto");
}
