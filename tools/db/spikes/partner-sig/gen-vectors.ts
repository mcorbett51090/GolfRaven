// ----- ES256 --------------------------------------------------------------------------------------------------------------------------------
const SA = "software-authenticator";
const es: SoftwareAuthenticator[] = [];
for (let i = 0; i < N_ES; i++) es.push(await SoftwareAuthenticator.create("ES256"));
const esOther = await SoftwareAuthenticator.create("ES256");
for (const a of es) {
  const { msg, sig } = await assertion(a);
  const { x, y } = a.keyParams;
  row("ES256", "valid", true, x!, y!, msg, sig, SA);
}
{
  const a = es[0]!;
  const { msg, sig } = await assertion(a);
  const { x, y } = a.keyParams;
  const flip = (b: Uint8Array, at: number) => Uint8Array.from(b, (v, i) => (i === (at < 0 ? b.length + at : at) ? v ^ 1 : v));
  const [r, s] = derParts(sig);
  row("ES256", "valid-high-s (n - s: still a valid ECDSA signature; WebAuthn does not require low-s)", true, x!, y!, msg, derSig(r, bytesOf(N_P256 - bigOf(s), 32)), SA);
  row("ES256", "bad: last signature bit flipped", false, x!, y!, msg, flip(sig, -1), SA);
  row("ES256", "bad: one message bit flipped", false, x!, y!, flip(msg, 5), sig, SA);
  row("ES256", "bad: another authenticator's key", false, esOther.keyParams.x!, esOther.keyParams.y!, msg, sig, SA);
  row("ES256", "bad: r = 0", false, x!, y!, msg, derSig(new Uint8Array(32), s), SA);
  row("ES256", "bad: s = 0", false, x!, y!, msg, derSig(r, new Uint8Array(32)), SA);
  row("ES256", "bad: s = n", false, x!, y!, msg, derSig(r, bytesOf(N_P256, 32)), SA);
  row("ES256", "bad: r = n", false, x!, y!, msg, derSig(bytesOf(N_P256, 32), s), SA);
  row("ES256", "bad: DER with a redundant leading zero in r", false, x!, y!, msg, concat(Uint8Array.of(0x30, sig[1]! + 1, 0x02, sig[3]! + 1, 0x00), sig.slice(4)), SA);
  row("ES256", "bad: DER with trailing garbage", false, x!, y!, msg, concat(sig, Uint8Array.of(0)), SA);
  row("ES256", "bad: DER with the wrong outer tag", false, x!, y!, msg, concat(Uint8Array.of(0x31), sig.slice(1)), SA);
  row("ES256", "bad: raw r||s instead of DER", false, x!, y!, msg, concat(bytesOf(bigOf(r), 32), bytesOf(bigOf(s), 32)), SA);
  row("ES256", "bad: public key off the curve (y + 1)", false, x!, bytesOf(bigOf(y!) + 1n, 32), msg, sig, SA);
  row("ES256", "bad: public key coordinate x = p (not reduced)", false, bytesOf(P_P256, 32), y!, msg, sig, SA);
  row("ES256", "bad: empty signature", false, x!, y!, msg, new Uint8Array(0), SA);
}
// Degenerate public keys, signed with a tiny independent BigInt ECDSA (affine arithmetic, written separately from the SQL): d = 1 makes Q = G, so the
// verifier's precomputed G + Q is a DOUBLING (the P = Q branch of the add routine), and d = n - 1 makes Q = -G, so G + Q is the point at infinity
// (the P = -Q branch). Both must still verify; both exercise code that a random key never reaches.
{
  const GX = 0x6b17d1f2e12c4247f8bce6e563a440f277037d812deb33a0f4a13945d898c296n;
  const GY = 0x4fe342e2fe1a7f9b8ee7eb4a7c0f9e162bce33576b315ececbb6406837bf51f5n;
  type Pt = [bigint, bigint] | null;
  const mod = (a: bigint, m: bigint) => ((a % m) + m) % m;
  const inv = (a: bigint, m: bigint) => {
    let [r0, r1, s0, s1] = [mod(a, m), m, 1n, 0n];
    while (r1 !== 0n) {
      const q = r0 / r1;
      [r0, r1] = [r1, r0 - q * r1];
      [s0, s1] = [s1, s0 - q * s1];
    }
    return mod(s0, m);
  };
  const add = (a: Pt, b: Pt): Pt => {
    if (a === null) return b;
    if (b === null) return a;
    if (a[0] === b[0] && mod(a[1] + b[1], P_P256) === 0n) return null;
    const l = a[0] === b[0] ? mod((3n * a[0] * a[0] - 3n) * inv(2n * a[1], P_P256), P_P256) : mod((b[1] - a[1]) * inv(b[0] - a[0], P_P256), P_P256);
    const x = mod(l * l - a[0] - b[0], P_P256);
    return [x, mod(l * (a[0] - x) - a[1], P_P256)];
  };
  const mul = (k: bigint, pt: Pt): Pt => {
    let r: Pt = null;
    let q = pt;
    while (k > 0n) {
      if (k & 1n) r = add(r, q);
      q = add(q, q);
      k >>= 1n;
    }
    return r;
  };
  const sign = async (d: bigint, msg: Uint8Array): Promise<Uint8Array> => {
    const z = bigOf(await sha256(msg));
    for (;;) {
      const k = mod(bigOf(crypto.getRandomValues(new Uint8Array(32))), N_P256);
      if (k === 0n) continue;
      const r = mod(mul(k, [GX, GY])![0], N_P256);
      const sv = mod(inv(k, N_P256) * (z + r * d), N_P256);
      if (r !== 0n && sv !== 0n) return derSig(bytesOf(r, 32), bytesOf(sv, 32));
    }
  };
  for (const [label, d, qy] of [
    ["valid: public key = G (d = 1): G + Q is a doubling", 1n, GY],
    ["valid: public key = -G (d = n - 1): G + Q is the point at infinity", N_P256 - 1n, P_P256 - GY],
  ] as const) {
    const msg = crypto.getRandomValues(new Uint8Array(69));
    row("ES256", label, true, bytesOf(GX, 32), bytesOf(qy, 32), msg, await sign(d, msg), "bigint-ecdsa");
  }
}
