// tools/db/spikes/partner-sig/gen-vectors.ts
//
// Emits the test vectors for the database-side signature spike (partner_sig_spike.sql) as SQL INSERTs on stdout. Run by run.sh; needs only Deno and
// no network, no import map and no lockfile (the one import is the in-tree software authenticator, which itself imports nothing).
//
//   deno run tools/db/spikes/partner-sig/gen-vectors.ts [--es256-valid N] [--rs256-valid N] > vectors.sql
//
// Every vector carries `expect`: what a CORRECT verifier must answer. Valid signatures come from the software authenticator's real WebAuthn assertions
// (message = authenticatorData || SHA-256(clientDataJSON), the bytes a relying party verifies) or from Web Crypto directly; the refusals are one-fault
// mutations of a valid vector, or signatures deliberately built wrong (a SHA-384 DigestInfo, a Bleichenbacher-shaped padding). Keys are fresh on every
// run, so a pass is not an artefact of one lucky key; the one fixed vector is the RFC 6979 A.2.5 known answer, which does not depend on Web Crypto.

import { concat, fromB64u, SoftwareAuthenticator } from "../../../../supabase/tests/deno-unit/software-authenticator.ts";

const args = new Map<string, string>();
for (let i = 0; i < Deno.args.length; i += 2) args.set(Deno.args[i]!, Deno.args[i + 1]!);
const N_ES = Number(args.get("--es256-valid") ?? 10);
const N_RS = Number(args.get("--rs256-valid") ?? 6);

const hex = (b: Uint8Array) => Array.from(b, (x) => x.toString(16).padStart(2, "0")).join("");
const fromHex = (h: string) => Uint8Array.from(h.match(/../g) ?? [], (x) => parseInt(x, 16));
const lit = (b: Uint8Array) => `'\\x${hex(b)}'`;
const sha256 = async (d: Uint8Array) => new Uint8Array(await crypto.subtle.digest("SHA-256", d as Uint8Array<ArrayBuffer>));

function row(alg: "ES256" | "RS256", label: string, expect: boolean, k1: Uint8Array, k2: Uint8Array, msg: Uint8Array, sig: Uint8Array, source: string): void {
  console.log(`INSERT INTO spike_sig.vector (alg, label, expect, k1, k2, msg, sig, source) VALUES ('${alg}', '${label.replaceAll("'", "''")}', ${expect}, ${lit(k1)}, ${lit(k2)}, ${lit(msg)}, ${lit(sig)}, '${source}');`);
}

/** DER Ecdsa-Sig-Value from two big-endian magnitudes (minimal, positive). */
function derSig(r: Uint8Array, s: Uint8Array): Uint8Array {
  const int = (b: Uint8Array): Uint8Array => {
    let i = 0;
    while (i < b.length - 1 && b[i] === 0) i++;
    let v: Uint8Array = b.slice(i);
    if (v[0]! & 0x80) v = concat(Uint8Array.of(0), v);
    return concat(Uint8Array.of(0x02, v.length), v);
  };
  const body = concat(int(r), int(s));
  return concat(Uint8Array.of(0x30, body.length), body);
}

/** r, s from a DER signature produced by our own encoder (single-byte lengths). */
function derParts(sig: Uint8Array): [Uint8Array, Uint8Array] {
  const rl = sig[3]!;
  const r = sig.slice(4, 4 + rl);
  const sl = sig[5 + rl]!;
  return [r, sig.slice(6 + rl, 6 + rl + sl)];
}

const bigOf = (b: Uint8Array) => BigInt("0x" + (hex(b) || "0"));
const bytesOf = (n: bigint, len: number) => fromHex(n.toString(16).padStart(len * 2, "0"));
const N_P256 = 0xffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551n;
const P_P256 = 0xffffffff00000001000000000000000000000000ffffffffffffffffffffffffn;

async function assertion(auth: SoftwareAuthenticator): Promise<{ msg: Uint8Array; sig: Uint8Array }> {
  const challenge = crypto.getRandomValues(new Uint8Array(32));
  const r = await auth.assert({ rpId: "partners.example.test", origin: "https://partners.example.test", challenge });
  const authData = fromB64u(r.response.authenticatorData);
  const cd = fromB64u(r.response.clientDataJSON);
  return { msg: concat(authData, await sha256(cd)), sig: fromB64u(r.response.signature) };
}

console.log("-- generated by gen-vectors.ts; fresh keys on every run. Do not commit.");
